import {chromium} from 'playwright';
import {createServer} from 'node:http';
import {readFile} from 'node:fs/promises';
import {resolve,extname,sep} from 'node:path';
import assert from 'node:assert/strict';

export async function checkSparkBrowser(owner) {
  const root=resolve('public'),server=createServer(async(req,res)=>{
    const path=resolve(root,'.'+new URL(req.url,'http://localhost').pathname);
    if(!path.startsWith(root+sep)){res.writeHead(403).end();return;}
    try {res.setHeader('Content-Type',({'.js':'text/javascript','.html':'text/html','.css':'text/css','.svg':'image/svg+xml'})[extname(path)]||'application/octet-stream');res.end(await readFile(path));}
    catch {res.writeHead(404).end();}
  });
  await new Promise(done=>server.listen(0,'127.0.0.1',done));
  const origin=`http://127.0.0.1:${server.address().port}`,browser=await chromium.launch({headless:true,executablePath:process.env.QA_BROWSER_PATH});
  const context=await browser.newContext({viewport:{width:1280,height:900},serviceWorkers:'block',reducedMotion:'reduce'}),page=await context.newPage(),errors=[],functions=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('request',req=>{if(req.url().includes('cloudfunctions.net'))functions.push(req.url());});
  await context.addInitScript(()=>{localStorage.setItem('qa-auth',localStorage.getItem('qa-auth')||'alice');localStorage.setItem('nexus:theme','Темна');});
  await context.route('**/firebase-auth.js',route=>route.fulfill({contentType:'text/javascript',body:`
    const uid=localStorage.getItem('qa-auth');
    const user={uid,emailVerified:true,email:uid+'@example.test',displayName:uid,photoURL:'',metadata:{creationTime:new Date(1).toISOString(),lastSignInTime:new Date(1).toISOString()}};
    const auth={currentUser:user};
    export const getAuth=()=>auth,browserLocalPersistence={},setPersistence=async()=>{},onAuthStateChanged=(_,fn)=>{queueMicrotask(()=>fn(user));return ()=>{};};
  `}));
  await context.route('**/js/config.js',route=>route.fulfill({contentType:'text/javascript',body:`export const OWNER_UID=${JSON.stringify(owner)};export const firebaseConfig={apiKey:'demo-key',projectId:'demo-nexus-gymb',authDomain:'demo-nexus-gymb.firebaseapp.com',appId:'demo'};`}));
  await context.route('**/js/firebase.js',async route=>{
    const source=(await readFile('public/js/firebase.js','utf8')).replace('db = C.getFirestore(app);',`db = C.getFirestore(app);\n  C.connectFirestoreEmulator(db,'127.0.0.1',8085,{mockUserToken:{sub:localStorage.getItem('qa-auth'),user_id:localStorage.getItem('qa-auth'),email_verified:true,email:localStorage.getItem('qa-auth')+'@example.test'}});`);
    await route.fulfill({contentType:'text/javascript',body:source});
  });
  try {
    await page.goto(origin+'/achievements.html');
    await page.locator('.achievement-card.is-earned').first().waitFor();
    await page.waitForFunction(()=>!document.querySelector('.achievements-page>p[role="status"]'));
    assert.equal(await page.locator('.achievements-page .notice.error').count(),0);
    assert.equal(await page.locator('.achievement-card [data-id="ceo-praise"]').count(),0);
    await page.evaluate(uid=>localStorage.setItem('qa-auth',uid),owner);
    await page.goto(origin+'/admin.html');
    await page.locator('[data-admin-section="users"]>summary').click();
    await page.locator('[data-action="load-users"]').click();
    await page.waitForFunction(()=>!!document.querySelector('[data-action="admin-user"][data-id="alice"]'));
    if(!await page.locator('[data-admin-section="users"]').evaluate(e=>e.open))await page.locator('[data-admin-section="users"]>summary').click();
    await page.locator('[data-action="admin-user"][data-id="alice"]:visible').first().click();
    await page.locator('[data-action="admin-member-panel"][data-panel="awards"]').click();
    await page.locator('#admin-award-form').waitFor();
    await page.locator('#admin-award-form [name="medalId"]').selectOption('ceo-praise');
    await page.locator('#admin-award-form button[type="submit"]').click();
    await page.locator('[data-action="admin-revoke-achievement"][data-id="ceo-praise"]').waitFor();
    await page.screenshot({path:'.sites-runtime/spark-admin-achievements.png'});
    await page.evaluate(()=>localStorage.setItem('qa-auth','alice'));
    await page.goto(origin+'/achievements.html');
    await page.locator('.achievement-card [data-id="ceo-praise"]').waitFor();
    await page.locator('.achievement-card [data-id="ceo-praise"]').click();
    await page.locator('#achievement-ranking').check();
    await page.locator('[data-action="save-achievement-display"]').click();
    await page.waitForFunction(()=>document.querySelector('#toast')?.textContent.includes('Вітрину збережено'));
    await page.locator('[data-action="achievement-leaderboard-refresh"]').click();
    await page.locator('.achievement-leaderboard .is-you').waitFor();
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:'.sites-runtime/spark-achievements-mobile.png'});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    await page.locator('.achievement-history-item').first().waitFor();
    assert.match(await page.locator('.achievement-history').innerText(),/Історія нагород/);
    await page.goto(origin+'/home.html');
    await page.locator('.weekly-goal-card [data-action="weekly-goal"]').click();
    await page.locator('#weekly-goal-form [name="target"]').fill('5');
    await page.locator('#weekly-goal-form button[type="submit"]').click();
    await page.waitForFunction(()=>document.querySelector('.goal-count small')?.textContent.includes('5'));
    await page.reload();
    await page.waitForFunction(()=>document.querySelector('.goal-count small')?.textContent.includes('5'));
    await page.screenshot({path:'.sites-runtime/weekly-goals-mobile.png'});
    await page.locator('.gymbro-challenges [data-action="new-challenge"]').click();
    await page.locator('#gym-challenge-form [name="title"]').fill('Браузерний виклик');
    await page.locator('#gym-challenge-form [name="target"]').fill('2');
    await page.locator('#gym-challenge-form button[type="submit"]').click();
    await page.locator('.challenge-card').filter({hasText:'Браузерний виклик'}).waitFor();
    await page.evaluate(()=>localStorage.setItem('qa-auth','bob'));
    await page.goto(origin+'/home.html');
    await page.locator('.challenge-card').filter({hasText:'Браузерний виклик'}).getByRole('button',{name:'Прийняти',exact:true}).click();
    await page.locator('.challenge-card').filter({hasText:'Браузерний виклик'}).locator('.challenge-track').waitFor();
    await page.screenshot({path:'.sites-runtime/gymbro-challenge-mobile.png'});
    await page.evaluate(()=>localStorage.setItem('qa-auth','alice'));
    await page.goto(origin+'/workout.html?summary=experience-new');
    await page.locator('.workout-comparison .comparison-metrics').waitFor();
    await page.locator('.workout-reflection [data-action="workout-reflection"]').click();
    await page.locator('#workout-reflection-form [name="difficulty"]').fill('8');
    await page.locator('#workout-reflection-form [name="energy"]').fill('4');
    await page.locator('#workout-reflection-form [name="note"]').fill('Приватна нотатка браузера');
    await page.locator('#workout-reflection-form button[type="submit"]').click();
    await page.waitForFunction(()=>document.querySelector('.reflection-note')?.textContent.includes('Приватна нотатка браузера'));
    await page.screenshot({path:'.sites-runtime/workout-comparison-mobile.png',fullPage:true});
    await page.goto(origin+'/profile.html');
    await page.locator('[data-action="edit-profile-blocks"]').click();
    await page.locator('[data-layout-key="goals"] [data-direction="-1"]').click();
    await page.locator('[data-layout-key="comments"] input').uncheck();
    await page.locator('#profile-layout-form').screenshot({path:'.sites-runtime/profile-layout-editor-mobile.png'});
    await page.locator('#profile-layout-form button[type="submit"]').click();
    await page.waitForFunction(()=>document.querySelector('.profile-feed')?.firstElementChild?.classList.contains('weekly-goal-card'));
    await page.reload();
    await page.waitForFunction(()=>document.querySelector('.profile-feed')?.firstElementChild?.classList.contains('weekly-goal-card'));
    assert.equal(await page.locator('.profile-comments').count(),0);
    await page.evaluate(()=>localStorage.setItem('qa-auth','bob'));
    await page.goto(origin+'/profile.html?uid=alice');
    await page.locator('.profile-hero h1').waitFor();
    assert.equal(await page.locator('.weekly-goal-card,[data-action="edit-profile-blocks"]').count(),0);
    assert.equal((await page.locator('body').innerText()).includes('Приватна нотатка браузера'),false);
    await page.locator('.personal-records').waitFor();
    await page.evaluate(()=>localStorage.setItem('qa-auth','alice'));
    await page.goto(origin+'/profile.html');
    await page.locator('[data-action="edit-profile-blocks"]').click();
    await page.locator('[data-layout-key="records"] input').uncheck();
    await page.locator('#profile-layout-form button[type="submit"]').click();
    await page.waitForFunction(()=>!document.querySelector('#modal')?.open);
    await page.evaluate(()=>localStorage.setItem('qa-auth','bob'));
    await page.goto(origin+'/profile.html?uid=alice');
    await page.locator('.profile-hero h1').waitFor();
    assert.equal(await page.locator('.personal-records').count(),0);
    await page.evaluate(()=>localStorage.setItem('qa-auth','alice'));
    await page.goto(origin+'/profile.html');
    await page.locator('[data-action="edit-profile-blocks"]').click();
    await page.locator('[data-layout-key="records"] input').check();
    await page.locator('#profile-layout-form button[type="submit"]').click();
    await page.waitForFunction(()=>!document.querySelector('#modal')?.open);
    await page.locator('.repetition-records [data-count="12"]').click();
    await page.locator('.repetition-records .record-row').first().waitFor();
    assert.match(await page.locator('.repetition-records').innerText(),/65 кг × 12/);
    await page.locator('.repetition-records').screenshot({path:'.sites-runtime/repetition-records-mobile.png'});
    await page.goto(origin+'/home.html');
    await page.locator('.activity-calendar [data-action="activity-filter"][data-id="home"]').click();
    await page.waitForFunction(()=>document.querySelectorAll('.activity-heatmap [data-activity-scope="home"]').length>0);
    assert.equal(await page.locator('.activity-heatmap [data-activity-scope="main"]').count(),0);
    await page.locator('.activity-calendar [data-action="activity-filter"][data-id="all"]').click();
    await page.locator('.activity-heatmap [data-activity-scope="mixed"]').first().waitFor();
    await page.locator('.activity-calendar').screenshot({path:'.sites-runtime/activity-calendar-mobile.png'});
    await page.goto(origin+'/workout.html');
    await page.locator('[data-action="workout-alternatives"]').first().click();
    await page.locator('#replacement-reason').selectOption('busy');
    await page.locator('.workout-replacements [data-action="replace-exercise"][data-id="alternate-press"]').click();
    await page.locator('.temporary-replacement').waitFor();
    assert.match(await page.locator('.workout-title').innerText(),/Жим у тренажері/);
    await page.locator('[data-action="restore-today-exercise"]').click();
    await page.waitForFunction(()=>document.querySelector('.workout-title')?.textContent.includes('Жим штанги'));
    assert.match(await page.locator('.workout-title').innerText(),/Жим штанги/);
    await page.locator('[data-action="workout-alternatives"]').first().click();
    await page.locator('.workout-replacements [data-action="replace-exercise"][data-id="alternate-press"]').click();
    await page.waitForFunction(()=>document.querySelector('.workout-title')?.textContent.includes('Жим у тренажері')&&!document.querySelector('#modal')?.open);
    await page.locator('#set-form [name="weight"]').fill('20');
    await page.locator('#set-form [name="reps"]').fill('8');
    assert.equal(await page.locator('#set-form [name="weight"]').inputValue(),'20');
    await page.locator('#set-form .workout-save').click();
    await page.waitForFunction(()=>document.querySelectorAll('[data-action="restore-today-exercise"]').length===0);
    await page.waitForFunction(()=>document.querySelector('.workout-sets tbody tr')?.textContent.includes('20 кг'));
    await page.screenshot({path:'.sites-runtime/today-only-replacement-mobile.png',fullPage:true});
    await page.goto(origin+'/home.html');
    await page.locator('.meeting-polls [data-action="new-meeting-poll"]').click();
    await page.locator('#meeting-poll-form [name="title"]').fill('Узгоджуємо тренування');
    await page.locator('#meeting-poll-form button[type="submit"]').click();
    await page.locator('.meeting-poll').filter({hasText:'Узгоджуємо тренування'}).waitFor();
    await page.evaluate(()=>localStorage.setItem('qa-auth','bob'));
    await page.goto(origin+'/home.html');
    const poll=page.locator('.meeting-poll').filter({hasText:'Узгоджуємо тренування'});
    await poll.locator('input[name="choice"][value="1"]').check();
    await poll.locator('button[type="submit"]').click();
    await page.waitForFunction(()=>document.querySelector('#toast')?.textContent.includes('Відповідь збережено'));
    await page.evaluate(()=>localStorage.setItem('qa-auth','alice'));
    await page.goto(origin+'/home.html');
    const ownerPoll=page.locator('.meeting-poll').filter({hasText:'Узгоджуємо тренування'});
    await ownerPoll.locator('[data-action="close-meeting-poll"][data-index="1"]').click();
    await ownerPoll.locator('[data-action="poll-training-invite"]').waitFor();
    await ownerPoll.screenshot({path:'.sites-runtime/gymbro-meeting-poll-mobile.png'});
    await ownerPoll.locator('[data-action="poll-training-invite"]').click();
    assert.equal(await page.locator('#training-invite-form [name="date"]').evaluate(input=>input.readOnly),true);
    await page.locator('#training-invite-form button[type="submit"]').click();
    await ownerPoll.locator('[data-action="view-training-invite"]').waitFor();
    await page.evaluate(()=>localStorage.setItem('qa-auth','bob'));
    await page.goto(origin+'/home.html');
    await page.locator('.meeting-poll').filter({hasText:'Узгоджуємо тренування'}).locator('[data-action="view-training-invite"]').click();
    await page.locator('[data-action="respond-training-invite"][data-status="accepted"]').click();
    await page.waitForFunction(()=>document.querySelector('#modal')?.textContent.includes('Прийнято'));
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    assert.deepEqual(functions,[]);assert.deepEqual(errors,[]);
    console.log('Spark browser passed: achievements, weekly goals, workout comparison, reflections, GymBro challenge invitation and acceptance, profile layout persistence and visitor privacy.');
  } catch(error) {await page.screenshot({path:'.sites-runtime/spark-browser-failure.png'});throw error;}
  finally {await browser.close();await new Promise(done=>server.close(done));}
}
