const escaped=Object.keys(english).sort((a,b)=>b.length-a.length).map(key=>key.replace(/[.*+?^${}()|[\]\\]/g,'\\$&'));
const phrases=new RegExp('(?<![\\p{L}])(?:'+escaped.join('|')+')(?![\\p{L}])','gu');
const translatedParts=new Map();
export function uiText(text) {
  text=String(text??'');
  if(getLanguage()!=='en')return text;
  if(!translatedParts.has(text)) translatedParts.set(text,text.replace(phrases,match=>english[match]));
  return translatedParts.get(text);
}
export function ui(parts,...values) {
  return parts.reduce((html,part,index)=>html+uiText(part)+(index<values.length?values[index]:''),'');
}
