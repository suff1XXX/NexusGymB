const item = (id) => {
  const e = exercises[id],
    timed = ["Кардіо", "Розминка", "Прес"].includes(e.primary);
  return {
    exerciseId: id,
    name: e.name,
    primary: e.primary,
    sets: timed ? 1 : 3,
    reps: timed ? "" : "10–12",
    seconds: e.primary === "Прес" ? 30 : timed ? 300 : 0,
    weight: 0,
    rest: timed ? 0 : 60,
    note: "Демонстраційне навантаження — налаштуй під себе.",
    snapshot: e,
  };
};
